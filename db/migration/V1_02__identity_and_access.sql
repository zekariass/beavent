-- =============================================================================
-- 02: identity & access
-- One account per person across the consumer app, web, partner portal and
-- admin console. Phone-first (most users in the launch markets have a phone
-- number before an email address). Organization roles live in tenant.*;
-- platform staff roles live here.
-- =============================================================================

CREATE TABLE iam.users (
  id                  uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  phone_e164          text UNIQUE CHECK (phone_e164 ~ '^\+[1-9][0-9]{6,14}$'),
  email               citext UNIQUE,
  phone_verified_at   timestamptz,
  email_verified_at   timestamptz,
  status              text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('PENDING','ACTIVE','LOCKED','SUSPENDED','CLOSED','MERGED')),
  merged_into_user_id uuid REFERENCES iam.users(id),
  country_code        char(2) REFERENCES ref.countries(code),
  preferred_language  text REFERENCES ref.languages(code),
  timezone            text,
  display_calendar    text CHECK (display_calendar IN ('GREGORIAN','ETHIOPIAN')),
  last_login_at       timestamptz,
  closed_at           timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CHECK (phone_e164 IS NOT NULL OR email IS NOT NULL OR status IN ('CLOSED','MERGED')),
  CHECK ((status = 'MERGED') = (merged_into_user_id IS NOT NULL))
);

CREATE TABLE iam.user_profiles (
  user_id        uuid PRIMARY KEY REFERENCES iam.users(id) ON DELETE CASCADE,
  first_name     text,
  last_name      text,
  display_name   text,
  date_of_birth  date,
  gender         text CHECK (gender IN ('FEMALE','MALE','OTHER','UNDISCLOSED')),
  avatar_file_id uuid REFERENCES platform.files(id),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE iam.user_addresses (
  id            uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id       uuid NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
  label         text NOT NULL,                   -- Home, Office, Mum's place
  country_code  char(2) NOT NULL REFERENCES ref.countries(code),
  admin_area_id uuid REFERENCES ref.administrative_areas(id),
  address_line  text,
  landmark      text,                            -- "behind Edna Mall, 2nd gate"
  instructions  text,
  geo           geography(Point, 4326),
  is_default    boolean NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_addresses_one_default ON iam.user_addresses (user_id) WHERE is_default;

CREATE TABLE iam.user_credentials (
  user_id              uuid PRIMARY KEY REFERENCES iam.users(id) ON DELETE CASCADE,
  password_hash        text NOT NULL,            -- Argon2id encoded string
  password_changed_at  timestamptz NOT NULL DEFAULT now(),
  must_change          boolean NOT NULL DEFAULT false,
  failed_attempts      smallint NOT NULL DEFAULT 0,
  locked_until         timestamptz
);

CREATE TABLE iam.user_identities (
  id             uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id        uuid NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
  provider       text NOT NULL CHECK (provider IN ('GOOGLE','APPLE','TELEGRAM','FACEBOOK','FAYDA')),
  subject        text NOT NULL,
  provider_email citext,
  linked_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, subject),
  UNIQUE (user_id, provider)
);

CREATE TABLE iam.mfa_factors (
  id            uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id       uuid NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
  kind          text NOT NULL CHECK (kind IN ('TOTP','SMS','WEBAUTHN')),
  label         text,
  secret_ref    text,                            -- secret manager reference; never the secret
  confirmed_at  timestamptz,
  last_used_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE iam.devices (
  id            uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id       uuid REFERENCES iam.users(id) ON DELETE SET NULL,
  installation_id text NOT NULL UNIQUE,          -- generated by the app on first launch
  platform      text NOT NULL CHECK (platform IN ('IOS','ANDROID','WEB')),
  push_token    text UNIQUE,
  app_version   text,
  locale        text,
  last_seen_at  timestamptz,
  disabled_at   timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE iam.sessions (
  id                 uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id            uuid NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
  client_app         text NOT NULL CHECK (client_app IN ('MOBILE_APP','WEB_MARKETPLACE','PARTNER_PORTAL','ADMIN_CONSOLE')),
  device_id          uuid REFERENCES iam.devices(id),
  -- Rotation family: every refresh issues a new row in the same family. Reuse of
  -- a rotated token revokes the whole family (token theft detection).
  family_id          uuid NOT NULL,
  refresh_token_hash text NOT NULL UNIQUE,
  rotated_at         timestamptz,
  assurance_level    text NOT NULL DEFAULT 'PASSWORD' CHECK (assurance_level IN ('OTP','PASSWORD','MFA','STEP_UP')),
  ip_address         inet,
  user_agent         text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  last_used_at       timestamptz,
  expires_at         timestamptz NOT NULL,
  revoked_at         timestamptz,
  revoke_reason      text CHECK (revoke_reason IN ('LOGOUT','ROTATED','REUSE_DETECTED','ADMIN','PASSWORD_CHANGED','ACCOUNT_CLOSED','EXPIRED'))
);
CREATE INDEX sessions_user_idx ON iam.sessions (user_id) WHERE revoked_at IS NULL;
CREATE INDEX sessions_family_idx ON iam.sessions (family_id);

CREATE TABLE iam.auth_challenges (
  id               uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id          uuid REFERENCES iam.users(id) ON DELETE CASCADE,
  purpose          text NOT NULL CHECK (purpose IN ('SIGN_UP','LOGIN','VERIFY_PHONE','VERIFY_EMAIL','RESET_PASSWORD','MFA','STEP_UP','CLAIM_GUEST_ORDERS','CHANGE_PAYOUT_ACCOUNT')),
  channel          text NOT NULL CHECK (channel IN ('SMS','WHATSAPP','TELEGRAM','EMAIL','TOTP','VOICE')),
  destination_hash text,                         -- HMAC of normalized phone/email; raw value not stored
  code_hash        text NOT NULL,
  attempts         smallint NOT NULL DEFAULT 0,
  max_attempts     smallint NOT NULL DEFAULT 5,
  expires_at       timestamptz NOT NULL,
  consumed_at      timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (attempts <= max_attempts)
);
CREATE INDEX auth_challenges_destination_idx ON iam.auth_challenges (destination_hash, created_at DESC);

CREATE TABLE iam.user_consents (
  id                  uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id             uuid NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
  document_version_id uuid NOT NULL REFERENCES ref.legal_document_versions(id),
  accepted_at         timestamptz NOT NULL DEFAULT now(),
  client_app          text,
  ip_address          inet,
  UNIQUE (user_id, document_version_id)
);

-- -----------------------------------------------------------------------------
-- Permissions: one catalog used by both organization roles (scope ORGANIZATION)
-- and platform staff roles (scope PLATFORM).
-- -----------------------------------------------------------------------------
CREATE TABLE iam.permissions (
  code        text PRIMARY KEY,                  -- 'appointments.manage', 'payouts.request', 'admin.kyb.decide'
  scope       text NOT NULL CHECK (scope IN ('ORGANIZATION','PLATFORM')),
  module      text NOT NULL,
  description text NOT NULL,
  is_sensitive boolean NOT NULL DEFAULT false    -- requires MFA / step-up
);

CREATE TABLE iam.staff_roles (
  code        text PRIMARY KEY,                  -- SUPER_ADMIN, OPS_ADMIN, SUPPORT_AGENT, FINANCE, RISK_ANALYST, MODERATOR, MARKET_MANAGER, READ_ONLY
  name        text NOT NULL,
  description text
);

CREATE TABLE iam.staff_role_permissions (
  role_code       text NOT NULL REFERENCES iam.staff_roles(code) ON DELETE CASCADE,
  permission_code text NOT NULL REFERENCES iam.permissions(code),
  PRIMARY KEY (role_code, permission_code)
);

CREATE TABLE iam.user_staff_roles (
  id          uuid PRIMARY KEY DEFAULT platform.uuid_v7(),
  user_id     uuid NOT NULL REFERENCES iam.users(id),
  role_code   text NOT NULL REFERENCES iam.staff_roles(code),
  market_id   uuid REFERENCES ref.markets(id),   -- NULL = all markets
  granted_by  uuid REFERENCES iam.users(id),
  granted_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz,
  revoked_at  timestamptz
);
CREATE UNIQUE INDEX user_staff_roles_active_uniq
  ON iam.user_staff_roles (user_id, role_code, coalesce(market_id, '00000000-0000-0000-0000-000000000000'::uuid))
  WHERE revoked_at IS NULL;

ALTER TABLE platform.files
  ADD CONSTRAINT files_owner_user_fk FOREIGN KEY (owner_user_id) REFERENCES iam.users(id);
